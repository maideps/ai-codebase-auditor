import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import type { AuditReport } from "../report/model.js";
import { buildHarnessFiles, type HarnessFilesInput } from "./files.js";

// The report snapshot: red src/auth, the yellow path src/engine.js, a plan with red-paths and yellow-paths items.
const report = JSON.parse(readFileSync(new URL("../report/__snapshots__/sample-report.json", import.meta.url), "utf8")) as AuditReport;
const input: HarnessFilesInput = {
  tool: report.tool, auditDate: report.auditDate, commit: report.target.head, verdict: report.verdict.verdict,
  plan: report.plan, zones: report.zones, roadmap: report.roadmap,
};
const fileOf = (files: ReturnType<typeof buildHarnessFiles>, name: string) => files.find((f) => f.path === `harness/${name}`)?.content ?? "";

describe("buildHarnessFiles", () => {
  const files = buildHarnessFiles(input);

  it("writes five files under harness/, sorted, deterministic", () => {
    expect(files.map((f) => f.path)).toEqual([
      "harness/AGENTS.snippet.md", "harness/README.md", "harness/characterization-tests.md", "harness/claude-settings.json", "harness/roadmap-checks.json",
    ]);
    expect(buildHarnessFiles(input)).toEqual(files);
    for (const file of files) expect(file.content.endsWith("\n") && !file.content.endsWith("\n\n")).toBe(true);
  });

  it("denies edits and writes to each red path, and maps each rule to its red path in the README", () => {
    expect(JSON.parse(fileOf(files, "claude-settings.json"))).toEqual({ permissions: { deny: ["Edit(src/auth/**)", "Write(src/auth/**)"] } });
    expect(fileOf(files, "README.md")).toContain("| `Edit(src/auth/**)` | `src/auth/` | auth |");
  });

  it("turns every plan item into an AGENTS.md rule citing its trigger", () => {
    const snippet = fileOf(files, "AGENTS.snippet.md");
    for (const item of report.plan.items) expect(snippet).toContain(`### ${item.id} (${item.level}; `);
    expect(snippet).toContain("### red-paths (required; red zone: 1 path)");
    expect(snippet).toContain("### yellow-paths (required; yellow zone: 1 path)");
    expect(snippet).toContain("### typed-changes (required; type-strictness scored 1)");
    expect(snippet).toContain(`Generated by ai-codebase-auditor 0.1.0 from the audit of ${report.auditDate}, commit ${report.target.head?.slice(0, 12)}`);
  });

  it("lists yellow modules and yellow paths as a checklist, or says there are none", () => {
    expect(fileOf(files, "characterization-tests.md")).toContain("- [ ] `src/engine.js` (in `src/(files)`): hotspot: 6 commits");
    const withModule = buildHarnessFiles({ ...input, zones: { ...input.zones, modules: [...input.zones.modules, { module: "lib", zone: "yellow", reason: "test-feedback 2 < 3", sourceFiles: 4, redFiles: 0, hotspots: [] }] } });
    expect(fileOf(withModule, "characterization-tests.md")).toContain("- [ ] `lib` (4 source files): test-feedback 2 < 3");
    const none = buildHarnessFiles({ ...input, zones: { ...input.zones, yellowPaths: [], redPaths: [] } });
    expect(fileOf(none, "characterization-tests.md")).toContain("Nothing to do: no yellow modules or yellow paths.");
    expect(JSON.parse(fileOf(none, "claude-settings.json"))).toEqual({ permissions: { deny: [] } });
    expect(fileOf(none, "README.md")).toContain("None: the audit found no red paths.");
  });

  it("gives each roadmap step the score a re-audit should show", () => {
    const checks = JSON.parse(fileOf(files, "roadmap-checks.json")) as { checks: { order: number; factor: string; from: number; minScore: number }[] };
    expect(checks.checks.map((c) => [c.order, c.factor, c.from, c.minScore])).toEqual(report.roadmap.map((step, index) => [index + 1, step.factor, step.from, step.to]));
  });

  it("says when the plan has no items", () => {
    const empty = buildHarnessFiles({ ...input, plan: { ...input.plan, items: [] } });
    expect(fileOf(empty, "AGENTS.snippet.md")).toContain("No adaptations: the plan has no items.");
  });
});
